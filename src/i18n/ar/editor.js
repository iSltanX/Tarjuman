/** صيغة العدد: one وtwo وfew وmany وsingle كما في formatCount. @param {number} n */
const form = (n) => {
  if (n === 1) return 'one';
  if (n === 2) return 'two';
  const mod = n % 100;
  if (mod >= 3 && mod <= 10) return 'few';
  return mod >= 11 ? 'many' : 'single';
};

