// التنقية الموحدة للنص الوارد من خارج الإضافة: نص الالتقاط، ونص ملف SRT المرفوع، وعنوان الفيديو، قبل التخزين وقبل التصدير.
// تزيل ما يخفي نصًا أو يقلب عرضه ولا يحتاجه أي نص مشروع:
// - الكتلة U+E0000–U+E0FFF عدا مكمّل محددات التنويع: محارف الوسوم (نص لا يُرى يصل إلى النموذج، ومقبول أن يصير علم التقسيمات
//   الفرعية علمًا أسود)، وغير المعيّن المتجاهَل افتراضيًا (ع-١٧).
// - محدد التنويع (U+FE00–U+FE0F ومكمّله U+E0100–U+E01EF) إلا بعد محرف له به تسلسلات تنويع مسجّلة (التحقق الأخير لـ2.3.0 ص-٣،
//   وقرار المالك في ن-٤): U+FE0E وU+FE0F بعد الإيموجي (\p{Emoji}: عرضه النصي أو الملوّن، ومنه مفاتيح الأرقام، والإيموجي في
//   تسلسلات ZWJ وبعد لون البشرة)، وU+E0100–U+E01EF بعد الأيديوغراف الموحّد (\p{Unified_Ideograph}، أساس IVD: 葛 مع U+E0100)،
//   وU+FE00–U+FE0D بعد أساس في جدول التنويعات القياسية (STANDARDIZED أدناه). فيُزال بعد الحرف اللاتيني والعربي وسائر الحروف،
//   وبعد محدد آخر متتابعًا، وفي أول النص أو السطر، وبعد مسافة أو تحكم أو تنسيق كـZWJ وRLM أو علامة ضامة كـCGJ؛ فلا تعبر حمولة
//   مرمّزة لا تُرى، لا متتابعةً (ع-١٧) ولا موزّعةً محددًا بعد كل حرف من نص ظاهر (ص-٣). وما بقي ممكنًا وحجمه في القيود المعروفة.
// - تضمين الاتجاه وتجاوزه U+202A–U+202E، وعزله U+2066–U+2069.
// - WJ ومحارف الرياضيات الخفية U+2060–U+2064، والمهملة U+206A–U+206F، وعلامات التعليق U+FFF9–U+FFFB (ع-١٧).
// - U+FEFF في أي موضع؛ وBOM في أول الملف يزيله المحلّل قبل وصول النص إلى هنا.
// - البديل اليتيم (نصف زوج UTF-16) ليس نصًا: يُزال من كل قطعة قبل وصلها، فلا يلتئم بديلان من قطعتين محرفًا مخفيًا (ع-١٧).
// وتبقى ZWSP وZWNJ وZWJ وLRM وRLM (U+200B–U+200F): مشروعة في الفارسية والأردية والتايلاندية وتسلسلات الإيموجي.
// (تُبنى من نص بتهريب مضاعف ليبقى المصدر مقروءًا بلا محارف خفية حرفية.)
// ومحدد التنويع ليس في مجموعة أساس، فلا يكون أساسًا لتاليه. والمسح على النص الأصلي، فكل محدد بعد الأول في تتابع يُزال، وكذلك
// المحدد بعد محرف يُزال (وسم أو اتجاه).
//
// أساس U+FE00–U+FE0D: تقريب لجدول StandardizedVariants.txt (لا نسخة منه في المستودع)، من خصائص يونيكود في المحرك ومن الكتل التي
// يغطيها الجدول. وأي محدد من U+FE00–U+FE0D يبقى بعد أي أساس منها، والجدول يستعمل أوّلها غالبًا.
// - أوسع من الجدول (يبقى بعده محدد لا يحتاجه نص، فيحمل بضع بتّات): الأيديوغراف الموحّد كله، والجدول نحو ألف منه (التنويعات
//   التوافقية لـCJK)؛ والميانمارية والفاغسبا والمانوية بكتاباتها كلها، والجدول حروف منها؛ والهيروغليفية المصرية (التدوير) عدا
//   محارف تنسيقها؛ وكتلتا عوامل الرياضيات U+2200–U+22FF وU+2A00–U+2AFF، والجدول نحو عشرين منها؛ والحروف الرياضية المنسوخة
//   U+1D49C–U+1D4CF ونظائرها الثمانية في U+2100–U+214F، والجدول كبارها (chancery وroundhand).
// - وبعينه: ترقيم شرق آسيا U+3001 وU+3002 وU+FF01 وU+FF0C وU+FF0E وU+FF1A وU+FF1B وU+FF1F، والصفر المشطور U+0030.
// - وأضيق إن كان في الجدول ما ليس هنا (يُزال محدد مشروع، فيُعرض شكل المحرف الافتراضي ولا يضيع من النص شيء): القائمة من معرفة
//   الجدول حتى يونيكود 16، لا من الملف. وعلامات الاقتباس المنحنية U+2018 وU+2019 وU+201C وU+201D ليست أساسًا عمدًا وإن كان لها
//   تنويع عرض شرق آسيوي: هي في كل نص إنجليزي، فتصير قناة.
const STANDARDIZED = [
  '\\p{Unified_Ideograph}',
  '\\p{Script=Myanmar}\\p{Script=Phags_Pa}\\p{Script=Manichaean}',
  '\\u{13000}-\\u{1342F}\\u{13460}-\\u{143FF}',
  '\\u2200-\\u22FF\\u2A00-\\u2AFF',
  '\\u210B\\u2110\\u2112\\u211B\\u212C\\u2130\\u2131\\u2133\\u{1D49C}-\\u{1D4CF}',
  '\\u3001\\u3002\\uFF01\\uFF0C\\uFF0E\\uFF1A\\uFF1B\\uFF1F',
  '0',
].join('');
const HIDDEN = new RegExp(
  '[\\u{E0000}-\\u{E00FF}\\u{E01F0}-\\u{E0FFF}\\u202A-\\u202E\\u2060-\\u2064\\u2066-\\u2069\\u206A-\\u206F\\uFEFF\\uFFF9-\\uFFFB\\uD800-\\uDFFF]'
  + '|(?<!\\p{Emoji})[\\uFE0E\\uFE0F]'
  + `|(?<![${STANDARDIZED}])[\\uFE00-\\uFE0D]`
  + '|(?<!\\p{Unified_Ideograph})[\\u{E0100}-\\u{E01EF}]',
  'gu',
);
// محارف التحكم C0 وC1 عدا الجدول وفواصل الأسطر والصفحات (مسافات يوحّدها التحويل): ليست نصًا. تُزال بـcontrols من نص الالتقاط
// ومن ملف الأصل المصدَّر (ع-١٧)؛ والمحلّل المتسامح يزيلها بنفسه بملاحظتها (IM_NOTE_CONTROL)، فلا تُعدّ عنده محارف مخفية.
const CONTROLS = new RegExp('[\\u0000-\\u0008\\u000E-\\u001F\\u007F-\\u009F]', 'gu');

/**
 * @param {string} text
 * @param {{ controls?: boolean }} [o] controls: وتُزال محارف التحكم C0 وC1 أيضًا
 * @returns {{ text: string, removed: number }} النص بعد التنقية وعدد المحارف المزالة
 */
export function sanitizeText(text, { controls = false } = {}) {
  let removed = 0;
  const drop = () => {
    removed++;
    return '';
  };
  let clean = String(text).replace(HIDDEN, drop);
  if (controls) clean = clean.replace(CONTROLS, drop);
  return { text: clean, removed };
}

/**
 * تنقية نصوص مقاطع؛ المقطع السليم يبقى هو نفسه.
 * @template {{ text: string }} C
 * @param {C[]} cues
 * @param {{ controls?: boolean }} [o] كما في sanitizeText
 * @returns {{ cues: C[], removed: number }}
 */
export function sanitizeCues(cues, o) {
  let removed = 0;
  const out = cues.map((c) => {
    const r = sanitizeText(c.text, o);
    removed += r.removed;
    return r.removed ? { ...c, text: r.text } : c;
  });
  return { cues: out, removed };
}
