// معكوسًا (تدقيق 7a66f91، U41).
const LTR = (s) => `${String.fromCodePoint(0x2066)}${s}${String.fromCodePoint(0x2069)}`;
const TIME_EXAMPLE = LTR('00:00:01,000 --> 00:00:03,500');
// زمن WebVTT بنقطة، والساعات اختيارية (تحقق 2.3.0، ص-١٤).
const VTT_TIME_EXAMPLE = LTR('00:00:01.000 --> 00:00:03.500');
const VTT_SHORT_EXAMPLE = LTR('00:01.000 --> 00:03.500');
/**
 * «مقطع واحد» و«مقطعين» و«3 مقاطع» و«11 مقطعًا» و«100 مقطع» بعد حرف جر (مجرور)، بقاعدة formatCount نفسها؛ ولا تُستورد هنا لأن
 * src/ui/format.js يقرأ الفهرس الذي يحمّل هذا الملف.
 * @param {number} n
 */
const cuesAfterPreposition = (n) => {
  if (n === 1) return 'مقطع واحد';
  if (n === 2) return 'مقطعين';
  const mod = n % 100;
  if (mod >= 3 && mod <= 10) return `${n} مقاطع`;
  return mod >= 11 ? `${n} مقطعًا` : `${n} مقطع`;
};
