// تعليمات النموذج (R10، P3-AC4): نص عربي ثابت يرسله المستخدم مع الملف إلى النموذج الذي يختاره. يطلب ترجمة
// النص وحده، ويحفظ الأرقام والتوقيتات حرفيًا، ويمنع الدمج والتقسيم والحذف والإضافة، ويذكر عدد المقاطع
// والوضع. التعليمات تقلل أخطاء النموذج ولا تضمن شيئًا؛ المقارن في الاستيراد (P4) هو الحكم.
import { COUNT_FORMS, formatCount } from '../../ui/format.js';

const MODE_LINES = Object.freeze({
  normal: 'عادي (مقاطع قصيرة تتبع إيقاع الكلام)',
  long: 'مقاطع أطول (كل مقطع حتى سطرين، وقد يضم أكثر من جملة)',
});

/**
 * @param {{ count: number, mode: 'normal' | 'long', parts?: { index: number, from: number, to: number }[] | null }} spec
 *   parts: أجزاء التقسيم الاحتياطي إن وُجدت، فتُذكر مع الترقيم المستمر
 * @returns {string}
 */
export function instructions({ count, mode, parts = null }) {
  if (!Number.isInteger(count) || count < 1) throw new RangeError(`عدد مقاطع غير صالح: ${count}`);
  if (!(mode in MODE_LINES)) throw new RangeError(`وضع تصدير غير معروف: ${mode}`);
  const cues = formatCount(count, COUNT_FORMS.cue);
  const lines = [
    'ترجم ملف الترجمة (SRT) المرفق من الإنجليزية إلى العربية الفصحى الواضحة، مراعيًا سياق الملف كله.',
    '',
    parts ? `عدد المقاطع الكلي: ${cues}، في ${parts.length} أجزاء.` : `عدد المقاطع في الملف: ${cues}.`,
    `وضع الملف: ${MODE_LINES[mode]}.`,
  ];
  if (parts) {
    lines.push(
      `الملف مقسّم إلى أجزاء بترقيم مستمر: ${parts.map((p) => `الجزء ${p.index} (المقاطع ${p.from}–${p.to})`).join('، ')}.`,
      'أرسل كل جزء بدوره، وأبقِ ترقيم كل جزء كما هو؛ لا تبدأ الترقيم من 1 في الأجزاء اللاحقة.',
    );
  }
  lines.push(
    '',
    'التزم بما يلي حرفيًا:',
    '1. ترجم نص المقاطع وحده.',
    '2. انسخ أرقام المقاطع وسطور التوقيت (مثل 00:00:27,103 --> 00:00:29,678) كما هي حرفيًا، بأرقام لاتينية 0-9، دون أي تعديل.',
    parts
      ? '3. لا تدمج مقطعين في مقطع، ولا تقسّم مقطعًا إلى اثنين، ولا تحذف مقطعًا ولا تضف مقطعًا: يجب أن يحوي ناتج كل جزء مقاطع جزئه نفسها بالترقيم نفسه وبالترتيب نفسه.'
      : `3. لا تدمج مقطعين في مقطع، ولا تقسّم مقطعًا إلى اثنين، ولا تحذف مقطعًا ولا تضف مقطعًا: يجب أن يحوي ناتجك ${cues} بالترقيم نفسه وبالترتيب نفسه.`,
    '4. أبقِ كل مقطع في سطر أو سطرين كما هو في الأصل ما أمكن.',
    '5. أعد ملف SRT وحده، بلا شرح قبله أو بعده وبلا علامات تنسيق (مثل ```).',
  );
  return lines.join('\n');
}
