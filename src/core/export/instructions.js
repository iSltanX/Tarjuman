export const TITLE_UNAVAILABLE = 'غير متوفر';

const PART_FORMS = Object.freeze({ one: 'جزء واحد', two: 'جزأين', few: 'أجزاء', many: 'جزءًا', single: 'جزء' });

// فواصل الأسطر والجداول تصير مسافة (لتبقى الكلمات منفصلة)، ثم تُجرَّد محارف التحكم والمحارف الخفية: فواصل الصفر
// والاتجاهات (LRM وRLM وALM وعوازل الاتجاه) وأسوار الاتجاه والوصل والقواطع الناعمة وBOM. (تُبنى من نص بتهريب مضاعف
// ليبقى المصدر مقروءًا بلا محارف خفية حرفية.)
const LINE_BREAKS = new RegExp('[\\r\\n\\t\\u0085\\u2028\\u2029\\u000B\\u000C]+', 'g');
const INVISIBLE = new RegExp(
  '[\\u0000-\\u001F\\u007F-\\u009F\\u00AD\\u034F\\u061C\\u115F\\u1160\\u17B4\\u17B5\\u180B-\\u180E\\u200B-\\u200F'
  + '\\u202A-\\u202E\\u2060-\\u206F\\u3164\\uFE00-\\uFE0F\\uFEFF\\uFFA0\\uFFF9-\\uFFFB]',
  'g',
);

/**
 * العنوان بيانات لا تعليمات: سطر واحد بلا محارف خفية ولا تحكم ولا مسافات متتالية، وبحد النموذج. الغائب أو الفارغ
 * بعد التجريد «غير متوفر». هذه الدالة لا تفسّر شيئًا في العنوان (لا قوالب ولا وسوم).
 * @param {unknown} title
 * @returns {string}
 */
export function cleanTitle(title) {
  if (typeof title !== 'string') return TITLE_UNAVAILABLE;
  const one = title.replace(LINE_BREAKS, ' ').replace(INVISIBLE, '').replace(/\s+/g, ' ').trim();
  const clipped = one.length > LIMITS.maxTitleChars ? Array.from(one).slice(0, LIMITS.maxTitleChars).join('').trim() : one;
  return clipped || TITLE_UNAVAILABLE;
}

/**
 * رابط المشاهدة من المعرّف بعد التحقق منه؛ المعرّف غير الصالح لا رابط له (فلا نسخ).
 * @param {string} videoId
 */
function watchLink(videoId) {
  if (!isVideoId(videoId)) throw new TjError('TJ_BAD_VIDEO_ID');
  return `https://www.youtube.com/watch?v=${videoId}`;
}

/** @param {{ index: number, from: number, to: number }[]} parts */
function partsParagraph(parts) {
  const ok = Array.isArray(parts) && parts.length >= 2
    && parts.every((p) => Number.isInteger(p?.index) && Number.isInteger(p.from) && Number.isInteger(p.to) && p.from >= 1 && p.to >= p.from);
  if (!ok) throw new RangeError('أجزاء تقسيم غير صالحة');
  return [
    `عدد المقاطع الكلي: ${formatCount(parts.at(-1).to, COUNT_FORMS.cue)}، في ${formatCount(parts.length, PART_FORMS)}.`,
    `الملف مقسّم إلى أجزاء بترقيم مستمر: ${parts.map((p) => `الجزء ${p.index} (المقاطع ${p.from}–${p.to})`).join('، ')}.`,
    'أرسل كل جزء بدوره، وأبقِ ترقيم كل جزء كما هو؛ لا تبدأ الترقيم من 1 في الأجزاء اللاحقة. يجب أن يحوي ناتج كل جزء مقاطع جزئه نفسها بالترقيم نفسه وبالترتيب نفسه.',
  ].join('\n');
}

/**
 * نص تعليمات الترجمة لفيديو: الملحق أ بعنوانه ورابطه، واستبدال المتغيرين بمرور واحد على القالب (فلا يُوسَّع متغير
 * يرد داخل العنوان). فقرة الأجزاء تُلحق عند التقسيم الاحتياطي وحده. يرمي TjError(TJ_BAD_VIDEO_ID) لمعرّف غير صالح.
 * @param {{ videoId: string, title?: string | null, parts?: { index: number, from: number, to: number }[] | null }} spec
 * @returns {string}
 */
export function instructions({ videoId, title, parts = null }) {
  const values = { video_title: cleanTitle(title), video_url: watchLink(videoId) };
  const text = INSTRUCTIONS_TEMPLATE.replace(/\{\{(video_title|video_url)\}\}/g, (_, key) => values[key]);
  return parts ? `${text}\n\n${partsParagraph(parts)}` : text;
}
